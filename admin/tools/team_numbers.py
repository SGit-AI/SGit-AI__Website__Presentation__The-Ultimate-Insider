#!/usr/bin/env python3
"""The team in numbers: one JSON of public counts for the talk's prelude, how this was made.

    python3 admin/tools/team_numbers.py        writes team/conductor/team-in-numbers.json

Reads only public records: git history (commit times and subjects' member prefix), the release tags,
team/*/wakes/*.json (outcomes), team/*/ROLE.md (the title line), team/*/key.json (the public
fingerprint, as on /admin/keys.html), team/conductor/schedule.json (slots) and the night snapshots
(letters as counts). Never a key, a read key, a vault id or a message body.
Kept by conductor@the-ultimate-insider; motion@ animates it.
"""
import datetime as dt, glob, json, re, subprocess
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT  = ROOT / 'team' / 'conductor' / 'team-in-numbers.json'


def git(*a):
    return subprocess.run(['git', *a], cwd=ROOT, capture_output=True, text=True).stdout


def main():
    now     = dt.datetime.now(dt.timezone.utc)
    log     = [l.split('\x1f') for l in git('log', '--no-merges', '--format=%cI\x1f%s').splitlines() if l]
    first   = min(t for t, _ in log)
    by_hour = Counter(t[:13] for t, _ in log)
    who     = Counter((re.match(r'@([\w.-]+):', s).group(1).replace('.', '-') if re.match(r'@([\w.-]+):', s) else 'other') for _, s in log)
    tags    = [t for t in git('tag', '--sort=creatordate').split() if t.startswith('v')]
    wakes   = [json.loads(Path(f).read_text()) for f in glob.glob(str(ROOT / 'team/*/wakes/*.json'))]
    slots   = {r['agent']: r['minute'] for r in json.loads((ROOT / 'team/conductor/schedule.json').read_text())['runs']}
    members = []
    for p in sorted(ROOT.glob('team/*/key.json')):
        aid  = p.parent.name
        k    = json.loads(p.read_text())
        lines = [l.strip() for l in (p.parent / 'ROLE.md').read_text().split('\n')] if (p.parent / 'ROLE.md').exists() else []
        role = next((l.split('. ')[0].rstrip('.') for l in lines[1:] if l and not l.startswith(('#', '-', '|', '>'))), '')   # the role's first sentence, in its own words
        own  = [t for t, s in log if s.startswith(f'@{aid.replace("-", ".")}:') or s.startswith(f'@{aid}:')]
        members.append(dict(id=aid, role=role, slot=slots.get(aid), key=k.get('fingerprint'), joined=min(own) if own else k.get('created'),
                            commits=who.get(aid, 0), wakes=sum(1 for w in wakes if w.get('agent') == aid)))
    letters = sum(len(json.loads(Path(f).read_text()).get('mail', [])) for f in glob.glob(str(ROOT / 'team/conductor/night/*.json')))
    data = dict(
        about='Public counts for the prelude of The ultimate insider: how this was made. Generated by admin/tools/team_numbers.py from the repository\'s public records.',
        as_of=now.strftime('%Y-%m-%dT%H:%M:%SZ'),
        first_commit=first,
        hours_since_first_commit=round((now - dt.datetime.fromisoformat(first)).total_seconds() / 3600, 1),
        commits=len(log), releases=len(tags), first_release=tags[0] if tags else None, latest_release=tags[-1] if tags else None,
        commits_overnight_22_to_06_utc=sum(n for h, n in by_hour.items() if h[11:13] in ('22', '23', '00', '01', '02', '03', '04', '05')),
        commits_by_hour=dict(sorted(by_hour.items())),
        wakes=len(wakes), wakes_by_outcome=dict(Counter(w.get('outcome') or 'open' for w in wakes)),
        five_step_verdicts=dict(Counter(v.get('verdict') for w in wakes for v in w.get('steps', {}).values())),
        holds=len(list(ROOT.glob('team/**/HOLD.md'))),
        letters_counted_by_the_night_log=letters,
        members=members,
        the_stack=['SGit vaults (sgit.ai) as the board and the mail', 'the PKI (pki.sgit.ai): every member\'s session key, vault keys sealed to it',
                   'the five-step wake with its gate', 'GitHub for the code, CI numbering every release'])
    OUT.write_text(json.dumps(data, indent=1) + '\n')
    print(f'wrote {OUT.relative_to(ROOT)}: {data["commits"]} commits, {data["releases"]} releases, {data["wakes"]} wakes, {len(members)} members, {data["hours_since_first_commit"]} h')


if __name__ == '__main__':
    main()
